#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { slugify, walk } from "./auto-discover-chrome.mjs";

const RECOGNIZED = [
  {
    slug: "multi-language",
    aliases: ["multi-language", "multilingual", "i18n", "internationalization", "localization", "language switching"],
    matcher: /\b(i18n|react-i18next|vue-i18n|getTranslations|getNavTranslations|languageChange|changeLanguage)\b/i,
    goal: "switch language on every authenticated chrome surface without losing app state",
  },
  {
    slug: "theme-switching",
    aliases: ["theme-switching", "theme switching", "dark mode", "light mode", "theme toggle"],
    matcher: /\b(ThemeProvider|useTheme|ThemeToggle|darkMode|setTheme|data-theme)\b/i,
    goal: "switch visual theme on every authenticated chrome surface without breaking layout or state",
  },
  {
    slug: "auth-state-recovery",
    aliases: ["auth-state-recovery", "auth state recovery", "session recovery", "oauth resume", "token refresh"],
    matcher: /\b(AuthContext|useAuth|OAuth|callback|refreshToken|tokenRefresh|signOut|onAuthStateChanged)\b/i,
    goal: "recover, refresh, and sign out cleanly from every entry point",
  },
  {
    slug: "multi-locale-payments",
    aliases: ["multi-locale-payments", "multi locale payments", "localized payments", "currency locale"],
    matcher: /\b(currency|locale|checkout|Stripe|payment|Intl\.NumberFormat)\b/i,
    goal: "complete checkout with the expected locale, currency, and payment state",
  },
  {
    slug: "accessibility",
    aliases: ["accessibility", "a11y", "keyboard navigation", "screen reader", "focus management"],
    matcher: /\b(aria-|role=|tabIndex|focus\(|focus-visible|screenReader|keyboard)\b/i,
    goal: "operate primary flows by keyboard and assistive technology without focus loss",
  },
];

function parseArgs(argv) {
  const flags = {
    root: process.cwd(),
    catalog: "docs/specs/capability-catalog.data.json",
    dryRun: false,
  };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === "--root") flags.root = argv[++i];
    else if (token === "--catalog") flags.catalog = argv[++i];
    else if (token === "--capability") flags.capability = argv[++i];
    else if (token === "--dry-run") flags.dryRun = true;
    else throw new Error(`Unknown argument: ${token}`);
  }
  return flags;
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function allSourceText(root) {
  const src = path.join(root, "src");
  return walk(src)
    .filter((file) => /\.(js|jsx|ts|tsx|vue|svelte)$/.test(file))
    .map((file) => fs.readFileSync(file, "utf8"))
    .join("\n");
}

function capabilityKey(capability) {
  return [
    capability.capability_id,
    capability.id,
    capability.name,
    capability.category,
    ...(capability.mechanics || []).map((item) => item.pattern),
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
}

function recognizedCapability(capability, requested) {
  const key = capabilityKey(capability);
  return RECOGNIZED.find((entry) => {
    if (requested && entry.slug !== slugify(requested) && !entry.aliases.includes(requested.toLowerCase())) {
      return false;
    }
    return entry.aliases.some((alias) => key.includes(alias));
  });
}

function isTableStakes(capability) {
  const frequency = String(capability.frequency || "").toLowerCase();
  const kano = String(capability.kano || "").toLowerCase();
  const depth = Number(capability.depth || 99);
  return frequency === "universal" || kano === "must-be" || depth <= 2;
}

function roleSurfaceRows() {
  return [
    ["customer", "mobile"],
    ["customer", "desktop"],
    ["owner", "mobile"],
    ["owner", "desktop"],
  ];
}

function journeyText(entry, capability) {
  const capId = capability.capability_id || capability.id || entry.slug;
  const title = `Capability ${entry.slug}: ${capability.name || capId}`;
  const scenarios = roleSurfaceRows()
    .map(([role, surface]) => {
      return `### Scenario: ${role} ${surface} coverage for ${entry.slug}

- Given I am signed in as a ${role} on ${surface}
- And I can see the application chrome for my current workspace
- When I use the ${capability.name || entry.slug} capability
- Then I can ${entry.goal}
- And the app remains interactive after the capability action completes`;
    })
    .join("\n\n");

  return `# ${title}

**Capability:** ${capId}
**Trace:** @capability:${entry.slug}
**Catalog Source:** @capability-source:${capId}

## Feature: ${title}

${scenarios}

## Coverage Notes

Generated by \`write-journeys --capability=${entry.slug}\` from \`docs/specs/capability-catalog.data.json\` after implementation-pattern detection confirmed the capability exists in code.
`;
}

function existingCapabilityCoverage(root, slug) {
  const dir = path.join(root, "docs/specs/journeys");
  if (!fs.existsSync(dir)) return false;
  return walk(dir)
    .filter((file) => file.endsWith(".feature.md"))
    .some((file) => fs.readFileSync(file, "utf8").includes(`@capability:${slug}`));
}

export function generateCapabilityJourneys(options) {
  const root = path.resolve(options.root || process.cwd());
  const catalogPath = path.resolve(root, options.catalog || "docs/specs/capability-catalog.data.json");
  if (!fs.existsSync(catalogPath)) {
    throw new Error(`Capability catalog not found: ${path.relative(root, catalogPath)}`);
  }

  const catalog = readJson(catalogPath);
  const sourceText = allSourceText(root);
  const journeyDir = path.join(root, "docs/specs/journeys");
  const generated = [];
  const skipped = [];

  for (const capability of catalog.capabilities || []) {
    const entry = recognizedCapability(capability, options.capability);
    if (!entry) continue;

    const capId = capability.capability_id || capability.id || entry.slug;
    if (!isTableStakes(capability)) {
      skipped.push({ capability: capId, reason: "not_table_stakes" });
      continue;
    }
    if (!entry.matcher.test(sourceText)) {
      skipped.push({ capability: capId, reason: "implementation_pattern_not_detected" });
      continue;
    }
    if (existingCapabilityCoverage(root, entry.slug)) {
      skipped.push({ capability: capId, reason: "already_covered" });
      continue;
    }

    const fileName = `J-CAP-${entry.slug}.feature.md`;
    const target = path.join(journeyDir, fileName);
    generated.push({ capability: capId, slug: entry.slug, file: path.relative(root, target) });
    if (!options.dryRun) {
      fs.mkdirSync(journeyDir, { recursive: true });
      if (!fs.existsSync(target)) {
        fs.writeFileSync(target, journeyText(entry, capability));
      }
    }
  }

  return { generated, skipped };
}

function main() {
  const flags = parseArgs(process.argv.slice(2));
  const result = generateCapabilityJourneys(flags);
  console.log(JSON.stringify(result, null, 2));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
