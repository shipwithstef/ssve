#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

function parseArgs(argv) {
  const flags = { root: process.cwd() };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === "--root") {
      flags.root = argv[++i];
    } else if (token === "--dry-run") {
      flags.dryRun = true;
    } else {
      throw new Error(`Unknown argument: ${token}`);
    }
  }
  return flags;
}

export function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === ".git" || entry.name === ".worktrees") {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(jsx|tsx|vue|svelte)$/.test(entry.name)) out.push(full);
  }
  return out;
}

function walkAllFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === ".git" || entry.name === ".worktrees") {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkAllFiles(full, out);
    else out.push(full);
  }
  return out;
}

function candidateFiles(root) {
  const src = path.join(root, "src");
  return walk(src).filter((file) => {
    const base = path.basename(file);
    return /(Layout|Header|Sidebar|Nav|Chrome|Shell|Menu)/i.test(base);
  });
}

export function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60) || "control";
}

function surfaceFor(file) {
  return path.basename(file).replace(/\.(jsx|tsx|vue|svelte)$/, "");
}

function attrValue(text, names) {
  for (const name of names) {
    const match = text.match(new RegExp(`${name}=(["'{])([^"'{}]+)\\1`));
    if (match) return match[2].trim();
  }
  return null;
}

function textFromWindow(lines, index) {
  const joined = lines.slice(index, Math.min(lines.length, index + 4)).join(" ");
  const inline = joined.match(/>([^<>{}][^<>]{1,80})</);
  if (inline) return inline[1].replace(/\s+/g, " ").trim();
  return null;
}

function classify(line) {
  const patterns = [
    { regex: /<button\b/i, role: "button" },
    { regex: /<Select\b/i, role: "select" },
    { regex: /<DropdownMenu\b/i, role: "dropdown-menu" },
    { regex: /<Sheet\b/i, role: "sheet" },
    { regex: /<Drawer\b/i, role: "drawer" },
    { regex: /<a\b[^>]*\bhref=/i, role: "link" },
    { regex: /<Link\b/i, role: "link" },
    { regex: /<NavLink\b/i, role: "nav-link" },
  ];
  return patterns.find((pattern) => pattern.regex.test(line))?.role ?? null;
}

export function discoverControls(root) {
  const controls = [];
  for (const file of candidateFiles(root)) {
    const rel = path.relative(root, file);
    const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
    lines.forEach((line, index) => {
      const role = classify(line);
      if (!role) return;
      const label =
        attrValue(line, ["aria-label", "title", "label", "name"]) ??
        textFromWindow(lines, index) ??
        role;
      const surface = surfaceFor(file);
      const id = `${slugify(surface)}-${role}-${slugify(label)}`;
      controls.push({
        id,
        role,
        label,
        surface,
        rel,
        line: index + 1,
      });
    });
  }
  return controls;
}

export function existingCoverage(root, journeyDir) {
  const covered = new Set();
  if (!fs.existsSync(journeyDir)) return covered;
  for (const file of walkAllFiles(journeyDir)) {
    if (!file.endsWith(".feature.md")) continue;
    const text = fs.readFileSync(file, "utf8");
    for (const match of text.matchAll(/@chrome-control:([a-z0-9-]+)/g)) {
      covered.add(match[1]);
    }
  }
  return covered;
}

export function journeyText(control) {
  const title = `Chrome ${control.role}: ${control.label}`;
  return `# ${title}

**Source:** ${control.rel}:${control.line}
**Surface:** ${control.surface}
**Control:** ${control.label}
**Trace:** @chrome-control:${control.id}

## Feature: ${title}

### Scenario: ${control.label} remains usable from ${control.surface}

- Given I am viewing the ${control.surface} chrome
- When I interact with the "${control.label}" ${control.role}
- Then the control opens, navigates, or changes state as designed
- And the app remains interactive after the interaction completes

## Coverage Notes

This skeleton was generated by \`write-journeys --auto-discover-chrome\` from ${control.rel}:${control.line}. Replace generic assertions with product-specific expectations during journey refinement.
`;
}

function targetFileName(control) {
  return `Chrome-${control.role}-${slugify(control.surface)}-${slugify(control.label)}.feature.md`;
}

function summaryStatus(control, journeyDir, covered) {
  if (!covered.has(control.id)) return "generated";
  const target = path.join(journeyDir, targetFileName(control));
  if (fs.existsSync(target)) {
    const text = fs.readFileSync(target, "utf8");
    if (text.includes("write-journeys --auto-discover-chrome")) return "generated";
  }
  return "covered";
}

function main() {
  const flags = parseArgs(process.argv.slice(2));
  const root = path.resolve(flags.root);
  const journeyDir = path.join(root, "docs/specs/journeys");
  const controls = discoverControls(root);
  const covered = existingCoverage(root, journeyDir);
  const uncovered = controls.filter((control) => !covered.has(control.id));

  const summaryLines = [
    "# Chrome Journey Auto-Discovery Summary",
    "",
    `**Scanned root:** ${root}`,
    `**Controls found:** ${controls.length}`,
    `**New skeletons emitted:** ${flags.dryRun ? 0 : uncovered.length}`,
    "",
    "| Control | Role | Surface | Source | Status |",
    "|---|---|---|---|---|",
  ];

  fs.mkdirSync(journeyDir, { recursive: true });
  for (const control of controls) {
    const status = summaryStatus(control, journeyDir, covered);
    summaryLines.push(
      `| ${control.label} | ${control.role} | ${control.surface} | ${control.rel}:${control.line} | ${status} |`
    );
    if (covered.has(control.id) || flags.dryRun) continue;
    const fileName = targetFileName(control);
    const target = path.join(journeyDir, fileName);
    if (!fs.existsSync(target)) {
      fs.writeFileSync(target, journeyText(control));
    }
  }

  const summaryPath = path.join(journeyDir, "SUMMARY.md");
  if (!flags.dryRun) {
    fs.writeFileSync(summaryPath, `${summaryLines.join("\n")}\n`);
  }

  console.log(
    JSON.stringify(
      {
        controls_found: controls.length,
        generated: flags.dryRun ? 0 : uncovered.length,
        summary: path.relative(root, summaryPath),
        controls: controls.map((control) => ({
          id: control.id,
          role: control.role,
          label: control.label,
          source: `${control.rel}:${control.line}`,
        })),
      },
      null,
      2
    )
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
